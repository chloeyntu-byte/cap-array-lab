REGISTER_HELPERS = r'''
procedure(calRegSchematicPin(cv name direction xy)
 let((pm wire q)
  pm=dbOpenCellViewByType("basic" "iopin" "symbol" "" "r")
  schCreatePin(cv pm name direction nil xy "R0")
  q=list(xCoord(xy)+0.35 yCoord(xy))
  wire=car(schCreateWire(cv "draw" "full" list(xy q) 0.0625 0.0625 0))
  schCreateWireLabel(cv wire q name "centerCenter" "R0" "stick" 0.06 nil)
 ))
procedure(calRegSymbolPin(cv name direction xy)
 let((net term fig)
  net=dbCreateNet(cv name) term=dbCreateTerm(net name direction)
  fig=dbCreateRect(cv list("pin" "drawing") list(list(xCoord(xy)-0.025 yCoord(xy)-0.025) list(xCoord(xy)+0.025 yCoord(xy)+0.025)))
  dbCreatePin(net fig name)
 ))
procedure(calCreateRegister(lib cell bits variable)
 let((cv bus expression)
  bus=sprintf(nil "B<%d:0>" bits-1)
  cv=dbOpenCellViewByType(lib cell "schematic" "schematic" "w")
  calRegSchematicPin(cv bus "output" list(-2 1))
  calRegSchematicPin(cv "VSS" "inputOutput" list(-2 0))
  for(bit 0 bits-1
   expression=sprintf(nil "CAL_VDD*(floor(%s/%d)-2*floor(%s/%d))" variable expt(2 bit) variable expt(2 bit+1))
   calSource(cv sprintf(nil "VB%d" bit) list(mod(bit 8)*2 -2-floor(bit/8)*2) sprintf(nil "B<%d>" bit) "VSS" expression "0" "0")
  )
  schCheck(cv) dbSave(cv) dbClose(cv)
  cv=dbOpenCellViewByType(lib cell "symbol" "schematicSymbol" "w")
  dbCreateRect(cv list("device" "drawing") list(list(-1.2 -0.6) list(1.2 0.6)))
  dbCreateLine(cv list("device" "drawing") list(list(1.2 0) list(1.5 0)))
  dbCreateLine(cv list("device" "drawing") list(list(0 -0.6) list(0 -0.8)))
  calRegSymbolPin(cv bus "output" list(1.5 0))
  calRegSymbolPin(cv "VSS" "inputOutput" list(0 -0.8))
  dbCreateLabel(cv list("device" "drawing") list(0 0.2) "DEC / BIN" "centerCenter" "R0" "roman" 0.12)
  dbSave(cv) dbClose(cv)
 ))
'''
