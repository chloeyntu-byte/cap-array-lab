def spectrum(resonator=False):
    """Pi network: Cbank=0.5 pF+code*0.125 pF, two 0.1 pF shunts.

    Each capacitor has constant parallel G=2*pi*1 GHz*C/80.
    Resonator adds a lossless 2 nH parallel branch across P/N.
    """
    rows=[]
    for code in range(8):
        c=(.5+.125*code)*1e-12
        for i in range(101):
            f=.5e9+7.5e9*i/100;w=2*math.pi*f
            branch=complex(2*math.pi*1e9*c/80,w*c)
            if resonator:branch+=1/complex(0,w*2e-9)
            shunt=complex(2*math.pi*1e9*.1e-12/80,w*.1e-12)
            row=dict(point=code,BANK=code,frequency_Hz=f,G_S=(branch+shunt/2).real,B_S=(branch+shunt/2).imag)
            for key,y in [('11',branch+shunt),('12',-branch),('21',-branch),('22',branch+shunt)]:
                row['Y'+key+'_G_S']=y.real;row['Y'+key+'_B_S']=y.imag
            rows.append(row)
    return {'version':2,'rows':rows}


def project(resonator=False):
    p=new_project();p.update(workspace='',library='GENERIC',reference={'library':'GENERIC','cell':'ideal_array'},demo_model='resonator' if resonator else 'array')
    p['settings'].update(frequencies='1G, 2G, 3G',simulation_start='500M',simulation_stop='8G',simulation_points='101',simulation_sweep='linear')
    symbol={'library':'GENERIC','cell':'Ideal switched C','bbox':[-1.8,-1,1.8,1],
            'pins':[{'name':'PLUS','xy':[-1.8,0]},{'name':'MINUS','xy':[1.8,0]},{'name':'BANK<2:0>','xy':[0,1]}],
            'shapes':[{'kind':'rect','points':[-1.8,-1,1.8,1]}]}
    node=add_instance(p,symbol,x=700,y=220);node['roles']={'PLUS':'P','MINUS':'N','BANK<0>':'BANK<0>','BANK<1>':'BANK<1>','BANK<2>':'BANK<2>'}
    add_register(p,'BANK',3,'0:7',x=250,y=750)
    for net,x,y in [('P',700,1050),('N',1200,750)]:
        n=create_passive(p,'capq',x=x,y=y,props={'c':'100f','q':'80','fq':'1G'});n['roles']={'PLUS':net,'MINUS':'VSS'}
    if resonator:
        n=create_passive(p,'indq',x=700,y=1500,props={'l':'2n','q':'1000000'});n['roles']={'PLUS':'P','MINUS':'N'}
    raw=spectrum(resonator);p['private']={'spectrum':raw,'spectrum_data_sha256':_hash(raw)}
    return p


def _hash(data):
    return hashlib.sha256(json.dumps(data,sort_keys=True,separators=(',',':')).encode('utf-8')).hexdigest()


def make_workbook():
    book=workbook(project());first=book['pages'][0];first['id']='ideal_array';first['name']='Ideal capacitor array';book['active_page']=first['id']
    second=add_page(book,'Parallel LC resonance');second['id']='lc_resonance';second['project']=project(True)
    for page in book['pages']:
        p=page['project'];page['result']=cache(resample(p['private']['spectrum'],p['settings']['frequencies']),digest(p),'cartesian');page['result']['analysis']='sp'
        page['axis']='BANK';page['editor']={'tab':'results','zoom':.45,'pan':[135,35]}
        if p['demo_model']=='resonator':page['editor'].update(zoom=.35,pan=[200,35])
        page['measurement_view']='Resonance' if p['demo_model']=='resonator' else 'Capacitance'
    book['active_page']=first['id'];book['appearance']={'canvas':'black','plot':'black'}
    book['description']='Synthetic analytic replay only; no PDK or native simulation data. See examples/README.md.'
    return book


def write_examples(folder):
    folder=Path(folder);folder.mkdir(parents=True,exist_ok=True)
    (folder/'ideal_array.json').write_text(json.dumps(make_workbook(),indent=2,ensure_ascii=True)+'\n',encoding='utf-8')
    # S=(I-Z0*Y)*(I+Z0*Y)^-1 for the synthetic code-0 capacitor pi network.
    lines=['! Synthetic code-0 capacitor pi network, generated by caplab.demo','# Hz S RI R 50']
    for row in spectrum()['rows'][:101]:
        a=50*complex(row['Y11_G_S'],row['Y11_B_S']);b=50*complex(row['Y12_G_S'],row['Y12_B_S'])
        den=(1+a)*(1+a)-b*b
        s11=((1-a)*(1+a)+b*b)/den;s21=-2*b/den
        values=[s11,s21,s21,s11]
        lines.append('{:.12g} '.format(row['frequency_Hz'])+' '.join('{:.12g} {:.12g}'.format(v.real,v.imag) for v in values))
    (folder/'ideal_array.s2p').write_text('\n'.join(lines)+'\n',encoding='ascii')


def replay(app):
    """Exercise the existing worker/progress/result pipeline using analytic data."""
    pid=app.book['active_page'];page=app.page();p=copy.deepcopy(page['project']);resonator=p['demo_model']=='resonator'
    def work(backend):
        for code in range(8):
            if backend.cancelled.is_set():raise RuntimeError('Synthetic replay stopped. Run again to replay all codes.')
            backend.progress(dict(kind='simulation',completed=code,total=8,message='Synthetic replay code {}/7'.format(code),active=True))
            time.sleep(.15)
        raw=spectrum(resonator);p['private']={'spectrum':raw,'spectrum_data_sha256':_hash(raw)}
        backend.progress(dict(kind='simulation',completed=8,total=8,message='Synthetic replay complete',active=False))
        return resample(raw,p['settings']['frequencies'])
    def done(rows):
        page['project']['private']=p['private'];page['run_project']=p;page['result']=cache(rows,digest(p),'cartesian');page['result']['analysis']='sp'
        page.pop('last_error',None)
        if app.book['active_page']==pid:
            app.rows=rows;app.result_identity=digest(p);app.result_mode='cartesian';app.result_analysis='sp';app.show_results()
        app.status.set('Synthetic replay complete: 8 codes; no EDA tools used.')
    app.task(work,done,pid,kind='simulation',label='Synthetic analytic replay')


